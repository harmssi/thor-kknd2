#!/usr/bin/env python3
"""KKND2 building sprites each carry their own colour table. 0.1.0 drew every building with the Outpost's table,
which scrambled colours ("blurry" look). This writes mods/openkrush_gen2/rules/building-palettes.yaml: one palette per
building/wall MOBD (from the owner's files at runtime) + player-colour remap of its blue entries. Run after editing sequences."""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mods', 'openkrush_gen2')
out, pals = [], {}
for fac in ('survivors', 'evolved', 'series9'):
    for kind in ('buildings', 'walls'):
        seq = open(f'{ROOT}/sequences/{fac}-{kind}.yaml').read()
        actor = None
        for line in seq.splitlines():
            m = re.match(r'^([a-z0-9_]+):\s*$', line)
            if m: actor = m.group(1); continue
            m = re.match(r'^\t(idle|make0|damaged-idle):\s*sprites\|(\w+)\.mobd', line)
            if actor and m:
                mobd = m.group(2)
                pals[mobd] = True
                out.append(f'{actor}:\n\tRenderSprites:\n\t\tPlayerPalette: {mobd}_player\n')
                actor = None
rules = '# generated by thor/gen_building_palettes.py\n' + '\n'.join(out) + '\n^Palettes:\n'
for m in sorted(pals):
    rules += f'\tPaletteFromMobd@{m}:\n\t\tName: {m}\n\t\tFilename: sprites|{m}.mobd\n'
    rules += f'\tOverlayPlayerColorPalette@{m}_player:\n\t\tBasePalette: {m}\n\t\tBaseName: {m}_player\n\t\tAutoRemapBlue: true\n'
open(f'{ROOT}/rules/building-palettes.yaml', 'w').write(rules)
print(len(out), 'actors,', len(pals), 'palettes')
